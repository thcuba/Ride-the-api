"""
PCAP / PCAPNG Parser for Ride-the-API.

Parses packet captures containing decrypted or cleartext HTTP traffic
(such as those generated by Darwin_SSL_sniffer, Wireshark, ecapture, or tcpdump)
and reconstructs HTTP request/response pairs into portable .ride-capture.json format.
"""

from __future__ import annotations

import io
import json
import logging
import re
import uuid
from datetime import UTC, datetime
from typing import Any
from urllib.parse import parse_qsl, urlsplit

import json_repair

from core.pattern_db.schemas import (
    CaptureDB,
    CaptureDeviceInfo,
    CaptureMeta,
    CaptureSession,
    RawPairWithResponse,
    RawResponse,
)

logger = logging.getLogger(__name__)

HTTP_METHODS = {"GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"}
STANDARD_SERVER_PORTS = {80, 443, 8080, 8443, 8000, 8883}
MIN_HTTP_PARTS = 2


try:
    from scapy.layers.inet import IP, TCP
    from scapy.utils import rdpcap
except ImportError:
    IP = None  # type: ignore[assignment,misc]
    TCP = None  # type: ignore[assignment,misc]
    rdpcap = None  # type: ignore[assignment]


def _parse_body(body_bytes: bytes, headers: dict[str, str]) -> Any:  # noqa: ANN401
    """Parse HTTP body bytes into json, string, or base64."""
    if not body_bytes:
        return None

    try:
        text = body_bytes.decode("utf-8")
    except UnicodeDecodeError:
        try:
            text = body_bytes.decode("iso-8859-1")
        except Exception:
            return None

    content_type = headers.get("content-type", "").lower()
    stripped = text.strip()
    is_json = "json" in content_type or (
        stripped.startswith(("{", "[")) and stripped.endswith(("}", "]"))
    )
    if is_json:
        try:
            return json.loads(text)
        except Exception:
            try:
                return json_repair.repair_json(text, return_objects=True)
            except Exception:
                return text

    return text


def _extract_chunked_body(data: bytes, body_start: int, length: int) -> tuple[bytes, int]:
    """Parse HTTP chunked transfer encoding into raw decoded bytes."""
    chunk_idx = body_start
    body_chunks = []
    while chunk_idx < length:
        line_end = data.find(b"\r\n", chunk_idx)
        if line_end == -1:
            break
        line = data[chunk_idx:line_end].strip()
        try:
            chunk_len = int(line.split(b";")[0], 16)
        except ValueError:
            break
        if chunk_len == 0:
            chunk_idx = line_end + 2
            break
        chunk_data_start = line_end + 2
        chunk_data_end = chunk_data_start + chunk_len
        body_chunks.append(data[chunk_data_start:chunk_data_end])
        chunk_idx = chunk_data_end + 2
    return b"".join(body_chunks), chunk_idx


def _split_http_messages(data: bytes) -> list[tuple[bytes, bytes]]:
    """Split raw TCP stream data into (header_bytes, body_bytes) pairs."""
    messages: list[tuple[bytes, bytes]] = []
    idx = 0
    length = len(data)

    while idx < length:
        header_end = data.find(b"\r\n\r\n", idx)
        sep_len = 4
        if header_end == -1:
            header_end = data.find(b"\n\n", idx)
            sep_len = 2

        if header_end == -1:
            break

        header_bytes = data[idx:header_end]
        body_start = header_end + sep_len

        # Check Content-Length
        cl_match = re.search(rb"(?i)content-length:\s*(\d+)", header_bytes)
        if cl_match:
            cl = int(cl_match.group(1))
            body_end = min(body_start + cl, length)
            body_bytes = data[body_start:body_end]
            messages.append((header_bytes, body_bytes))
            idx = body_end
            continue

        # Check Chunked Transfer Encoding
        if re.search(rb"(?i)transfer-encoding:\s*chunked", header_bytes):
            chunked_bytes, next_idx = _extract_chunked_body(data, body_start, length)
            messages.append((header_bytes, chunked_bytes))
            idx = next_idx
            continue

        # If neither Content-Length nor Chunked is specified:
        first_line = header_bytes.split(b"\r\n", 1)[0]
        if any(first_line.startswith(m.encode("ascii") + b" ") for m in HTTP_METHODS):
            messages.append((header_bytes, b""))
            idx = body_start
        else:
            next_http = data.find(b"HTTP/1.", body_start)
            if next_http != -1:
                messages.append((header_bytes, data[body_start:next_http]))
                idx = next_http
            else:
                messages.append((header_bytes, data[body_start:]))
                idx = length

    return messages


def _parse_single_http_message(header_bytes: bytes, body_bytes: bytes) -> dict[str, Any] | None:
    """Parse header bytes and body bytes into a message dict."""
    try:
        header_text = header_bytes.decode("iso-8859-1")
    except Exception:
        return None

    lines = header_text.split("\r\n")
    if len(lines) == 1 and "\n" in header_text:
        lines = header_text.split("\n")

    if not lines or not lines[0].strip():
        return None

    first_line = lines[0].strip()
    headers: dict[str, str] = {}
    for line in lines[1:]:
        if ":" in line:
            k, v = line.split(":", 1)
            headers[k.strip().lower()] = v.strip()

    parts = first_line.split(" ", 2)
    # Check if Request: METHOD TARGET HTTP/X.X
    if parts[0].upper() in HTTP_METHODS and len(parts) >= MIN_HTTP_PARTS:
        method = parts[0].upper()
        target = parts[1]
        url_parts = urlsplit(target)
        path = url_parts.path or "/"
        if not path.startswith("/"):
            path = "/" + path
        query_params = dict(parse_qsl(url_parts.query, keep_blank_values=True))

        body = _parse_body(body_bytes, headers)
        return {
            "type": "request",
            "method": method,
            "path": path,
            "headers": headers,
            "query_params": query_params,
            "body": body,
        }

    # Check if Response: HTTP/X.X STATUS REASON
    if first_line.upper().startswith("HTTP/") and len(parts) >= MIN_HTTP_PARTS:
        try:
            status_code = int(parts[1])
        except ValueError:
            status_code = 200

        body = _parse_body(body_bytes, headers)
        return {
            "type": "response",
            "status_code": status_code,
            "headers": headers,
            "body": body,
        }

    return None


def _identify_endpoints(
    flow_pkts: list[Any],
    ip_cls: Any,  # noqa: ANN401
    tcp_cls: Any,  # noqa: ANN401
) -> tuple[Any, Any]:
    """Determine client and server endpoints from packet payloads or ports."""
    client_endpoint = None
    server_endpoint = None

    for pkt in flow_pkts:
        if hasattr(pkt, "load") and pkt.load:
            payload = bytes(pkt.load)
            first_word = payload.split(b" ", 1)[0].decode("ascii", errors="replace").upper()
            if first_word in HTTP_METHODS:
                ip_src = pkt[ip_cls].src if pkt.haslayer(ip_cls) else pkt["IPv6"].src
                client_endpoint = (ip_src, pkt[tcp_cls].sport)
                break
            if payload.startswith(b"HTTP/"):
                ip_src = pkt[ip_cls].src if pkt.haslayer(ip_cls) else pkt["IPv6"].src
                server_endpoint = (ip_src, pkt[tcp_cls].sport)
                break

    p0 = flow_pkts[0]
    ip_src = p0[ip_cls].src if p0.haslayer(ip_cls) else p0["IPv6"].src
    ip_dst = p0[ip_cls].dst if p0.haslayer(ip_cls) else p0["IPv6"].dst
    sport = p0[tcp_cls].sport
    dport = p0[tcp_cls].dport

    if not client_endpoint and not server_endpoint:
        if dport in STANDARD_SERVER_PORTS:
            client_endpoint = (ip_src, sport)
            server_endpoint = (ip_dst, dport)
        else:
            client_endpoint = (ip_src, sport)
            server_endpoint = (ip_dst, dport)
    elif client_endpoint and not server_endpoint:
        server_endpoint = (ip_dst, dport) if (ip_src, sport) == client_endpoint else (ip_src, sport)
    elif server_endpoint and not client_endpoint:
        client_endpoint = (ip_dst, dport) if (ip_src, sport) == server_endpoint else (ip_src, sport)

    return client_endpoint, server_endpoint


def parse_pcap_data(  # noqa: C901, PLR0912, PLR0915
    content: bytes,
    vendor: str = "sniffer",
    device_type: str = "iot",
    device_id: str = "obfuscated",
) -> CaptureDB:
    """Parse PCAP / PCAPNG bytes into a CaptureDB using Scapy."""
    if rdpcap is None or IP is None or TCP is None:
        err_msg = "scapy is required to parse PCAP/PCAPNG files. Run: pip install scapy"
        raise RuntimeError(err_msg)

    try:
        packets = rdpcap(io.BytesIO(content))
    except Exception as e:
        read_err_msg = f"Failed to read PCAP data: {e}"
        raise ValueError(read_err_msg) from e

    flows: dict[tuple, list[Any]] = {}
    for pkt in packets:
        if not pkt.haslayer(TCP):
            continue

        ip_src = (
            pkt[IP].src if pkt.haslayer(IP) else (pkt["IPv6"].src if pkt.haslayer("IPv6") else None)
        )
        ip_dst = (
            pkt[IP].dst if pkt.haslayer(IP) else (pkt["IPv6"].dst if pkt.haslayer("IPv6") else None)
        )
        if not ip_src or not ip_dst:
            continue

        tcp = pkt[TCP]
        endpoint_a = (ip_src, tcp.sport)
        endpoint_b = (ip_dst, tcp.dport)
        flow_key = tuple(sorted([endpoint_a, endpoint_b]))

        if flow_key not in flows:
            flows[flow_key] = []
        flows[flow_key].append(pkt)

    pairs: list[RawPairWithResponse] = []
    now = datetime.now(UTC)
    session_start = now

    for flow_pkts in flows.values():
        client_endpoint, _server_endpoint = _identify_endpoints(flow_pkts, IP, TCP)

        c2s_bytes = bytearray()
        s2c_bytes = bytearray()
        first_time = None

        for pkt in flow_pkts:
            if hasattr(pkt, "load") and pkt.load:
                ip_src = pkt[IP].src if pkt.haslayer(IP) else pkt["IPv6"].src
                ep = (ip_src, pkt[TCP].sport)
                if first_time is None and hasattr(pkt, "time"):
                    first_time = float(pkt.time)

                if ep == client_endpoint:
                    c2s_bytes.extend(pkt.load)
                else:
                    s2c_bytes.extend(pkt.load)

        if not c2s_bytes:
            continue

        req_messages = _split_http_messages(bytes(c2s_bytes))
        resp_messages = _split_http_messages(bytes(s2c_bytes))

        parsed_requests = []
        for h_bytes, b_bytes in req_messages:
            msg = _parse_single_http_message(h_bytes, b_bytes)
            if msg and msg.get("type") == "request":
                parsed_requests.append(msg)

        parsed_responses = []
        for h_bytes, b_bytes in resp_messages:
            msg = _parse_single_http_message(h_bytes, b_bytes)
            if msg and msg.get("type") == "response":
                parsed_responses.append(msg)

        for idx, req_msg in enumerate(parsed_requests):
            resp_msg = parsed_responses[idx] if idx < len(parsed_responses) else None

            raw_response = None
            if resp_msg:
                raw_response = RawResponse(
                    status_code=resp_msg["status_code"],
                    headers=resp_msg["headers"],
                    body=resp_msg["body"],
                    latency_ms=25.0,
                )

            pair_dt = now
            if first_time:
                try:
                    pair_dt = datetime.fromtimestamp(first_time, tz=UTC)
                except Exception:
                    pair_dt = now

            pair = RawPairWithResponse(
                pair_id=f"pair_{uuid.uuid4().hex[:12]}",
                timestamp=pair_dt,
                protocol="http",
                method=req_msg["method"],
                path=req_msg["path"],
                headers=req_msg["headers"],
                query_params=req_msg["query_params"],
                body=req_msg["body"],
                response=raw_response,
            )
            pairs.append(pair)

    if pairs:
        session_start = pairs[0].timestamp

    session = CaptureSession(
        session_id=f"session_{uuid.uuid4().hex[:10]}",
        type="capture",
        timestamp_start=session_start,
        pairs=pairs,
    )

    meta = CaptureMeta(
        version=1,
        capture_id=f"cap_pcap_{uuid.uuid4().hex[:8]}",
        vendor=vendor,
        device_type=device_type,
        model="",
        firmware_version="",
        capture_date=session_start,
        description="Imported from PCAP/PCAPNG capture",
    )

    device_info = CaptureDeviceInfo(
        device_id=device_id,
        mac="obfuscated",
        serial="obfuscated",
    )

    return CaptureDB(
        meta=meta,
        device_info=device_info,
        sessions=[session],
    )
